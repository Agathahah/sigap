-- Warehouse DDL (Postgres 16 + pgvector): star schema in `gold`, operational tables in `ops`.
-- Idempotent: every statement is CREATE ... IF NOT EXISTS, so `make gold` can run after every monthly drop.
-- Dimension keys are identity columns: a key never changes once assigned, so facts and ops rows stay valid
-- when new categories appear in a later month.
-- Grain of gold.fact_application: one row per account-opening application.

CREATE SCHEMA IF NOT EXISTS gold;
CREATE SCHEMA IF NOT EXISTS ops;

-- Dimensions -------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_month (
    month_key      INTEGER PRIMARY KEY,         -- = month_index; kept separate so a calendar can replace it
    month_index    SMALLINT NOT NULL UNIQUE,
    label_complete BOOLEAN  NOT NULL          -- false while fraud labels for the month have not arrived yet
);

CREATE TABLE IF NOT EXISTS gold.dim_channel (
    channel_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       TEXT NOT NULL,
    payment_type TEXT NOT NULL,
    UNIQUE (source, payment_type)
);

CREATE TABLE IF NOT EXISTS gold.dim_device (
    device_key         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_os          TEXT     NOT NULL,
    keep_alive_session SMALLINT NOT NULL,
    email_is_free      SMALLINT NOT NULL,
    UNIQUE (device_os, keep_alive_session, email_is_free)
);

-- age_band, income_decile and employment_status are protected attributes (ADR 0005): used for fairness
-- reporting only, never exposed to the copilot.
CREATE TABLE IF NOT EXISTS gold.dim_profile (
    profile_key       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    age_band          TEXT     NOT NULL,
    income_decile     SMALLINT NOT NULL,
    employment_status TEXT     NOT NULL,
    housing_status    TEXT     NOT NULL,
    UNIQUE (age_band, income_decile, employment_status, housing_status)
);

-- Fact -------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.fact_application (
    application_id                   TEXT PRIMARY KEY,
    month_key                        INTEGER NOT NULL REFERENCES gold.dim_month (month_key),
    channel_key                      INTEGER NOT NULL REFERENCES gold.dim_channel (channel_key),
    device_key                       INTEGER NOT NULL REFERENCES gold.dim_device (device_key),
    profile_key                      INTEGER NOT NULL REFERENCES gold.dim_profile (profile_key),
    name_email_similarity            DOUBLE PRECISION NOT NULL,
    prev_address_months_count        INTEGER NULL,   -- NULL = sentinel in the source, see *_missing
    current_address_months_count     INTEGER NULL,
    days_since_request               DOUBLE PRECISION NOT NULL,
    intended_balcon_amount           DOUBLE PRECISION NULL,
    zip_count_4w                     INTEGER NOT NULL,
    velocity_6h                      DOUBLE PRECISION NOT NULL,
    velocity_24h                     DOUBLE PRECISION NOT NULL,
    velocity_4w                      DOUBLE PRECISION NOT NULL,
    bank_branch_count_8w             INTEGER NOT NULL,
    date_of_birth_distinct_emails_4w INTEGER NOT NULL,
    credit_risk_score                INTEGER NOT NULL,
    phone_home_valid                 SMALLINT NOT NULL,
    phone_mobile_valid               SMALLINT NOT NULL,
    bank_months_count                INTEGER NULL,
    has_other_cards                  SMALLINT NOT NULL,
    proposed_credit_limit            DOUBLE PRECISION NOT NULL,
    foreign_request                  SMALLINT NOT NULL,
    session_length_in_minutes        DOUBLE PRECISION NULL,
    device_distinct_emails_8w        INTEGER NULL,
    prev_address_months_count_missing    SMALLINT NOT NULL,
    current_address_months_count_missing SMALLINT NOT NULL,
    intended_balcon_amount_missing       SMALLINT NOT NULL,
    bank_months_count_missing            SMALLINT NOT NULL,
    session_length_in_minutes_missing    SMALLINT NOT NULL,
    device_distinct_emails_8w_missing    SMALLINT NOT NULL,
    is_fraud                         SMALLINT NULL   -- NULL until the label has arrived (2-month lag)
        CHECK (is_fraud IN (0, 1))
);

CREATE INDEX IF NOT EXISTS ix_fact_month   ON gold.fact_application (month_key);
CREATE INDEX IF NOT EXISTS ix_fact_device  ON gold.fact_application (device_key);
CREATE INDEX IF NOT EXISTS ix_fact_profile ON gold.fact_application (profile_key);
CREATE INDEX IF NOT EXISTS ix_fact_channel ON gold.fact_application (channel_key);

-- Operational tables -----------------------------------------------------------------------------------------
-- One row per scoring decision (written by the API and the monthly replay). Append-only.
-- application_id is not a foreign key: the API decides before the application reaches the warehouse.
CREATE TABLE IF NOT EXISTS ops.decision_log (
    id             BIGSERIAL PRIMARY KEY,
    application_id TEXT NOT NULL,
    model_version  TEXT NOT NULL,
    score          DOUBLE PRECISION NOT NULL CHECK (score BETWEEN 0 AND 1),
    decision       TEXT NOT NULL CHECK (decision IN ('approve', 'review', 'decline')),
    reasons        TEXT[] NOT NULL DEFAULT '{}',   -- reason codes, never raw feature values
    decided_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE ops.decision_log DROP CONSTRAINT IF EXISTS decision_log_application_id_fkey;  -- databases created earlier
CREATE INDEX IF NOT EXISTS ix_decision_app  ON ops.decision_log (application_id);
CREATE INDEX IF NOT EXISTS ix_decision_time ON ops.decision_log (decided_at);

-- Monthly monitoring in long format: one value per (month, metric, feature).
-- metric: psi | alert_rate | review_rate | tpr | fpr ; feature = '' for metrics that are not per feature.
CREATE TABLE IF NOT EXISTS ops.monitoring_monthly (
    month       SMALLINT NOT NULL REFERENCES gold.dim_month (month_index),
    metric      TEXT NOT NULL,
    feature     TEXT NOT NULL DEFAULT '',
    value       DOUBLE PRECISION NOT NULL,
    computed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (month, metric, feature)
);
